#!/usr/bin/env python3
"""Generate a standalone C++ oracle compatible with GammaMax.

The generated program reads the complete candidate value from standard input.
It exits with 0 when the value is accepted, 1 when it is rejected, and 2 when
the oracle is invoked incorrectly.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import re
import sys
from typing import Any


INT64_MIN = -(2**63)
INT64_MAX = 2**63 - 1


def int64(value: Any, field: str) -> int:
    """Validate a JSON integer representable by C++ std::int64_t."""
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValueError(f"{field} must be a JSON integer")
    parsed = value
    if not INT64_MIN <= parsed <= INT64_MAX:
        raise ValueError(
            f"{field} must be between {INT64_MIN} and {INT64_MAX}"
        )
    return parsed


def finite_real(value: Any, field: str) -> float:
    """Validate a finite JSON number representable by a C++ double."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{field} must be a JSON number")
    parsed = float(value)
    if not math.isfinite(parsed):
        raise ValueError(f"{field} must be finite")
    return parsed


def cpp_string(value: str) -> str:
    """Encode arbitrary Unicode text as an unambiguous UTF-8 C++ literal."""
    pieces: list[str] = ['"']
    for byte in value.encode("utf-8"):
        if byte == ord('"'):
            pieces.append(r'\"')
        elif byte == ord("\\"):
            pieces.append(r"\\")
        elif 0x20 <= byte <= 0x7E:
            pieces.append(chr(byte))
        else:
            # Exactly three octal digits prevent following characters from being
            # consumed as part of the escape.
            pieces.append(f"\\{byte:03o}")
    pieces.append('"')
    return "".join(pieces)


def program(predicate_includes: str, predicate_body: str) -> str:
    """Wrap a predicate in GammaMax's external-oracle process protocol."""
    includes = "#include <iostream>\n#include <iterator>\n#include <string>\n"
    if predicate_includes:
        includes += predicate_includes
    return f"""// Generated by benchmark/oracles/oracle-gen.py. Do not edit manually.
{includes}
namespace {{

bool accepts(const std::string& value) {{
    if (value.empty() || value == "?" || value.find('#') != std::string::npos) return false;
{predicate_body}
}}

}}  // namespace

int main(int argc, char**) {{
    if (argc != 1) return 2;

    std::string input;
    input.assign(std::istreambuf_iterator<char>(std::cin), {{}});
    if (!std::cin.eof() && std::cin.fail()) return 2;
    return accepts(input) ? 0 : 1;
}}
"""


def integer_source(lower: int, upper: int) -> str:
    def literal(value: int) -> str:
        if value == INT64_MIN:
            return "std::numeric_limits<std::int64_t>::min()"
        if value == INT64_MAX:
            return "std::numeric_limits<std::int64_t>::max()"
        return str(value)

    lower_literal = literal(lower)
    upper_literal = literal(upper)
    body = f"""    std::int64_t parsed{{}};
    const char* begin = value.data();
    const char* const end = begin + value.size();
    if (begin != end && *begin == '+') ++begin;
    const auto result = std::from_chars(begin, end, parsed, 10);
    if (begin == end || result.ec != std::errc{{}} || result.ptr != end) return false;
    return parsed >= {lower_literal} && parsed <= {upper_literal};"""
    return program(
        "#include <charconv>\n#include <cstdint>\n#include <limits>\n",
        body,
    )


def real_source(lower: float, upper: float) -> str:
    # Hexadecimal literals reproduce the Python/C++ binary64 bounds exactly.
    lower_literal = lower.hex()
    upper_literal = upper.hex()
    body = f"""    double parsed{{}};
    const char* const begin = value.data();
    const char* const end = begin + value.size();
    const auto result = std::from_chars(begin, end, parsed, std::chars_format::general);
    if (value.empty() || result.ec != std::errc{{}} || result.ptr != end ||
        !std::isfinite(parsed)) return false;
    return parsed >= {lower_literal} && parsed <= {upper_literal};"""
    return program("#include <charconv>\n#include <cmath>\n", body)


def regex_source(expression: str) -> str:
    body = f"""    static const std::regex expression(
        {cpp_string(expression)}, std::regex::ECMAScript);
    return std::regex_match(value, expression);"""
    return program("#include <regex>\n", body)


def list_source(values: list[str]) -> str:
    entries = ",\n".join(f"        {cpp_string(value)}" for value in values)
    body = f"""    static const std::unordered_set<std::string> allowed{{
{entries}
    }};
    return allowed.contains(value);"""
    return program("#include <unordered_set>\n", body)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate GammaMax-compatible C++ oracles from a JSON manifest.",
        epilog="example: %(prog)s ../datasets/adult_20/oracles.json -o generated/adult_20",
    )
    parser.add_argument("manifest", type=Path, help="input JSON manifest")
    parser.add_argument(
        "-o",
        "--output-dir",
        type=Path,
        help="output directory (default: an 'oracles' folder beside the manifest)",
    )
    return parser


def required(config: dict[str, Any], key: str, context: str) -> Any:
    if key not in config:
        raise ValueError(f"{context} is missing required field {key!r}")
    return config[key]


def source_for(config: dict[str, Any], context: str) -> str:
    kind = required(config, "type", context)
    if kind == "integer":
        lower = int64(required(config, "minimum", context), f"{context}.minimum")
        upper = int64(required(config, "maximum", context), f"{context}.maximum")
        if lower > upper:
            raise ValueError(f"{context}.minimum must not exceed maximum")
        return integer_source(lower, upper)
    if kind == "real":
        lower = finite_real(required(config, "minimum", context), f"{context}.minimum")
        upper = finite_real(required(config, "maximum", context), f"{context}.maximum")
        if lower > upper:
            raise ValueError(f"{context}.minimum must not exceed maximum")
        return real_source(lower, upper)
    if kind == "regex":
        expression = required(config, "regex", context)
        if not isinstance(expression, str):
            raise ValueError(f"{context}.regex must be a string")
        return regex_source(expression)
    if kind == "list":
        values = required(config, "values", context)
        if not isinstance(values, list) or not values:
            raise ValueError(f"{context}.values must be a non-empty array")
        if any(not isinstance(value, str) for value in values):
            raise ValueError(f"every item in {context}.values must be a string")
        return list_source(list(dict.fromkeys(values)))
    raise ValueError(f"{context}.type must be integer, real, regex, or list")


def safe_stem(column: str) -> str:
    stem = re.sub(r"[^A-Za-z0-9_.-]+", "_", column).strip("._")
    if not stem:
        raise ValueError(f"cannot derive an output filename from column {column!r}")
    return stem


def load_manifest(path: Path) -> list[dict[str, Any]]:
    try:
        document = json.loads(path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as error:
        raise ValueError(f"invalid JSON in {path}: {error}") from error
    if not isinstance(document, dict):
        raise ValueError("manifest root must be a JSON object")
    oracles = required(document, "oracles", "manifest")
    if not isinstance(oracles, list) or not oracles:
        raise ValueError("manifest.oracles must be a non-empty array")
    if any(not isinstance(oracle, dict) for oracle in oracles):
        raise ValueError("every item in manifest.oracles must be an object")
    return oracles


def generate_manifest(manifest: Path, output_dir: Path) -> int:
    oracles = load_manifest(manifest)
    generated: list[tuple[Path, str]] = []
    destinations: set[Path] = set()
    for index, oracle in enumerate(oracles):
        context = f"manifest.oracles[{index}]"
        column = required(oracle, "column", context)
        if not isinstance(column, str) or not column:
            raise ValueError(f"{context}.column must be a non-empty string")
        output = oracle.get("output", f"{safe_stem(column)}.cpp")
        if not isinstance(output, str) or not output or Path(output).name != output:
            raise ValueError(f"{context}.output must be a plain filename")
        destination = output_dir / output
        if destination in destinations:
            raise ValueError(f"duplicate output filename: {output}")
        destinations.add(destination)
        generated.append((destination, source_for(oracle, context)))

    output_dir.mkdir(parents=True, exist_ok=True)
    for destination, source in generated:
        # `newline` is not accepted by pathlib.Path.write_text on older Python
        # versions. `source` is constructed with explicit `\n` line endings.
        destination.write_text(source, encoding="utf-8")
    return len(generated)


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        output_dir = args.output_dir or args.manifest.parent / "oracles"
        count = generate_manifest(args.manifest, output_dir)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(f"generated {count} oracle(s) in {output_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
